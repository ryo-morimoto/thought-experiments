"""Write GenRows.tla: scenarios (records for GenModel) and observed rows.

usage: python3 -I mkallowed.py <scenarios.tsv> <observed.tsv> <out dir>
Scen[s] is the scenario record; Rows[r] = [id, s, i (level, 1 = top), k (kind),
chrome, firefox] where chrome/firefox are the sets of observed values ({} if
not observed). Kind "onload" (auxiliary) is not mapped.
"""
import csv
import os
import sys

scen_tsv, obs_tsv, outdir = sys.argv[1:4]
BROWSERS = ["chrome", "firefox"]


def orig(s, h):
    return '[scheme |-> "%s", host |-> "%s", site |-> "%s"]' % (s, h, h[0])


def other(h):
    return "b" if h[0] == "a" else "a"


scen, idx = [], {}
with open(scen_tsv, encoding="utf-8") as f:
    for r in csv.DictReader(f, delimiter="\t"):
        d = int(r["depth"])
        lv = [r[c].split("/") for c in ("l1", "l2")][:d]   # s, rel, h, coep, corp
        o = [orig(r["top_scheme"], "a")] + [orig(x[0], x[2]) for x in lv]
        e = [r["top_coep"]] + [x[3] for x in lv]
        corp = ["none"] + [x[4] for x in lv]
        deepest = lv[-1][2] if lv else "a"
        while len(o) < 3:
            o.append(o[0]); e.append(e[0]); corp.append("none")
        idx[r["sid"]] = len(scen) + 1
        scen.append('[d |-> %d, coop |-> "%s", o |-> <<%s>>, e |-> <<%s>>, corp |-> <<%s>>, tgt |-> %s]' % (
            d, r["top_coop"], ", ".join(o), ", ".join('"%s"' % x for x in e),
            ", ".join('"%s"' % x for x in corp), orig("https", other(deepest))))

obs = {}
with open(obs_tsv, encoding="utf-8") as f:
    for r in csv.DictReader(f, delimiter="\t"):
        sid, lvl, kind = r["row"].rsplit(".", 2)
        if kind == "onload":
            continue
        obs.setdefault((sid, int(lvl), kind), {})[r["browser"]] = r["values"].split("|")

rows = []
for (sid, lvl, kind) in sorted(obs, key=lambda k: (idx[k[0]], k[1], k[2])):
    b = obs[(sid, lvl, kind)]
    sets = ["{%s}" % ", ".join('"%s"' % v for v in b.get(x, [])) for x in BROWSERS]
    rows.append('[id |-> "%s.%d.%s", s |-> %d, i |-> %d, k |-> "%s", chrome |-> %s, firefox |-> %s]' % (
        sid, lvl, kind, idx[sid], lvl + 1, kind, sets[0], sets[1]))

with open(os.path.join(outdir, "GenRows.tla"), "w", encoding="utf-8") as f:
    f.write("---- MODULE GenRows ----\n(* generated by gen/driver/mkallowed.py *)\n")
    f.write("Browsers == {%s}\n" % ", ".join('"%s"' % b for b in BROWSERS))
    f.write("Scen == <<\n  " + ",\n  ".join(scen) + ">>\n")
    f.write("Rows == <<\n  " + ",\n  ".join(rows) + ">>\n====\n")
print("scenarios", len(scen), "rows", len(rows))
