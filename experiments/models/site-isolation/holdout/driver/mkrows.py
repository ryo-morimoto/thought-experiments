"""Write HoldRows.tla: the observed rows of both families.

usage: python3 -I mkrows.py <holdout dir> <out dir>
Reads <holdout dir>/scenarios.tsv, <holdout dir>/observed.tsv and the test
files. NRows[r] = [id, x (index into NestSpace), i (level, 1 = top), k,
chrome, firefox]; RRows[r] = [id, x (index into RedirSpace), k, chrome,
firefox]. chrome/firefox are the sets of observed values over the repeats
({} if not observed). Not mapped: kind "error" (R) and the LATE line. The top
rows of an N file ("<file>.0.<kind>") are mapped once, to the file's first
scenario (every scenario of a file has the same top document).
"""
import csv
import os
import re
import sys

hdir, outdir = sys.argv[1:3]
BROWSERS = ["chrome", "firefox"]
idx, fam = {}, {}
with open(os.path.join(hdir, "scenarios.tsv"), encoding="utf-8") as f:
    for r in csv.DictReader(f, delimiter="\t"):
        idx[r["sid"]] = int(r["index"])
        fam[r["sid"]] = r["family"]
first = {}
tdir = os.path.join(hdir, "tests")
for name in sorted(os.listdir(tdir)):
    if name.startswith("n-") and name.endswith(".html"):
        m = re.search(r'\{id:"(n\d+)"', open(os.path.join(tdir, name), encoding="utf-8").read())
        first[name] = m.group(1)
obs = {}
with open(os.path.join(hdir, "observed.tsv"), encoding="utf-8") as f:
    for r in csv.DictReader(f, delimiter="\t"):
        row = r["row"]
        if row.startswith("r"):
            sid, kind = row.rsplit(".", 1)
            if kind == "error":
                continue
            key = ("R", sid, 0, kind)
        else:
            sid, lvl, kind = row.rsplit(".", 2)
            if sid.startswith("n-"):          # top rows of a file
                sid = first[sid]
            key = ("N", sid, int(lvl), kind)
        obs.setdefault(key, {})[r["browser"]] = r["values"].split("|")
nrows, rrows = [], []
for key in sorted(obs, key=lambda k: (k[0], idx[k[1]], k[2], k[3])):
    f_, sid, lvl, kind = key
    b = obs[key]
    sets = ["{%s}" % ", ".join('"%s"' % v for v in b.get(x, [])) for x in BROWSERS]
    if f_ == "N":
        nrows.append('[id |-> "%s.%d.%s", x |-> %d, i |-> %d, k |-> "%s", chrome |-> %s, firefox |-> %s]' % (
            sid, lvl, kind, idx[sid], lvl + 1, kind, sets[0], sets[1]))
    else:
        rrows.append('[id |-> "%s.%s", x |-> %d, k |-> "%s", chrome |-> %s, firefox |-> %s]' % (
            sid, kind, idx[sid], kind, sets[0], sets[1]))
with open(os.path.join(outdir, "HoldRows.tla"), "w", encoding="utf-8") as f:
    f.write("---- MODULE HoldRows ----\n(* generated by holdout/driver/mkrows.py *)\n")
    f.write("Browsers == {%s}\n" % ", ".join('"%s"' % b for b in BROWSERS))
    f.write("NRows == <<\n  " + ",\n  ".join(nrows) + ">>\n")
    f.write("RRows == <<\n  " + ",\n  ".join(rrows) + ">>\n====\n")
print("N rows", len(nrows), "R rows", len(rrows))
