"""Write HistoryRows.tla: observed rows of the run scenarios.

usage: python3 -I mkrows.py <scenarios.tsv> <observed.tsv> <out dir>
Rows[r] = [id, x (space index), k (kind), chrome, firefox, hchrome, hfirefox];
chrome/firefox are the sets of observed values ({} if not observed);
h<browser> is the set of bfcache-hit vectors the browser showed for the
scenario (product of the observed hit1/hit2 values; both values if a hit was
not observed). Kinds "error" and "odd" are not mapped.
Also WptRows: upstream WPT tests (driver/originals.txt) as scenarios with
their expected values, for the kill comparison.
"""
import csv
import itertools
import os
import sys

scen_tsv, obs_tsv, outdir = sys.argv[1:4]
BROWSERS = ["chrome", "firefox"]
NT = {"NB": 1, "NBF": 2, "NNB": 1, "NNB2": 1, "NBN": 1}
idx, nt = {}, {}
with open(scen_tsv, encoding="utf-8") as f:
    for r in csv.DictReader(f, delimiter="\t"):
        idx[r["sid"]] = int(r["index"])
        nt[r["sid"]] = NT[r["seq"]]
obs = {}
with open(obs_tsv, encoding="utf-8") as f:
    for r in csv.DictReader(f, delimiter="\t"):
        sid, kind = r["row"].rsplit(".", 1)
        if kind in ("error", "odd"):
            continue
        obs.setdefault((sid, kind), {})[r["browser"]] = r["values"].split("|")


def hits(sid, b):
    per = []
    for k in range(1, nt[sid] + 1):
        v = obs.get((sid, "hit%d" % k), {}).get(b)
        per.append(v if v else ["TRUE", "FALSE"])
    return "{%s}" % ", ".join("<<%s>>" % ", ".join(t) for t in itertools.product(*per))


rows = []
for (sid, kind) in sorted(obs, key=lambda k: (idx[k[0]], k[1])):
    b = obs[(sid, kind)]
    sets = ["{%s}" % ", ".join('"%s"' % v for v in b.get(x, [])) for x in BROWSERS]
    rows.append('[id |-> "%s.%s", x |-> %d, k |-> "%s", chrome |-> %s, firefox |-> %s, '
                'hchrome |-> %s, hfirefox |-> %s]' % (
                    sid, kind, idx[sid], kind, sets[0], sets[1], hits(sid, "chrome"), hits(sid, "firefox")))

# Upstream WPT tests on the same axes (codes of HistorySeq.tla), hit unknown.
# coop-navigated-history-popup: test page without COOP opens a popup at A
# (no COOP) that navigates to CROSS_ORIGIN with COOP same-origin and goes
# back (history.go(-1)); verify_window wants closed = TRUE and opener FALSE.
# websockets/back-forward-cache-*-open-websocket-connection: a noopener window
# at A opens a WebSocket, navigates away (same origin) and back; the
# non-tentative test wants no bfcache, the tentative one wants bfcache.
WPT = [
    ("coop-navigated-history-popup/opener", "<<1, 1, 1, <<<<1, 1, 1>>, <<2, 3, 1>>>>>>", "opener", "FALSE"),
    ("coop-navigated-history-popup/closed", "<<1, 1, 1, <<<<1, 1, 1>>, <<2, 3, 1>>>>>>", "closed", "TRUE"),
    ("ws-open-connection", "<<2, 1, 1, <<<<1, 1, 2>>, <<1, 1, 1>>>>>>", "hit1", "FALSE"),
    ("ws-closes-open-connection.tentative", "<<2, 1, 1, <<<<1, 1, 2>>, <<1, 1, 1>>>>>>", "hit1", "TRUE"),
]
with open(os.path.join(outdir, "HistoryRows.tla"), "w", encoding="utf-8") as f:
    f.write("---- MODULE HistoryRows ----\n(* generated by history/driver/mkrows.py *)\n")
    f.write("Browsers == {%s}\n" % ", ".join('"%s"' % b for b in BROWSERS))
    f.write("Rows == <<\n  " + ",\n  ".join(rows) + ">>\n")
    f.write("WptRows == <<\n  " + ",\n  ".join(
        '[id |-> "%s", sc |-> %s, k |-> "%s", want |-> "%s"]' % w for w in WPT) + ">>\n====\n")
print("rows", len(rows), "wpt", len(WPT))
