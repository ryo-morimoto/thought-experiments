"""Generator of the session-history / bfcache scenarios (history/RESULTS.md).

usage:
  python3 -I gen.py space <out dir>          write HistorySpace.tla (whole space)
  python3 -I gen.py select <tlc-enum.out> <history dir> [seed] [k] [k0]
        pick k scenarios per pre-screen class (k0 for classes no mutant
        distinguishes), write scenarios.tsv and tests/

Axes (codes as in HistorySeq.tla):
  st    popup (window.open(D1)) | noopener (window.open(D1, "_blank", "noopener"); opener COOP un)
  op    opener (test page at A) COOP: un, sap, so, so+rc
  seq   NB, NBF, NNB, NNB2, NBN (N: navigate to the next document, B/F: back/forward, B2: go(-2))
  doc   per document: relation to A {same-origin, cross-site} x COOP {un, sap, so, so+rc};
        documents that are traversal targets also get {no WebSocket, open WebSocket}
"""
import itertools
import os
import random
import re
import sys

ST = ["popup", "noopener"]
OP = ["unsafe-none", "same-origin-allow-popups", "same-origin", "so+rc"]
OPc = ["u", "p", "s", "c"]
REL = ["same-origin", "cross-site"]
RELc = ["O", "X"]
SEQ = ["NB", "NBF", "NNB", "NNB2", "NBN"]
OPS = {"NB": [0, -1], "NBF": [0, -1, 1], "NNB": [0, 0, -1], "NNB2": [0, 0, -2], "NBN": [0, -1, 0]}
TARGETS = {"NB": {0}, "NBF": {0, 1}, "NNB": {1}, "NNB2": {0}, "NBN": {0}}
CHUNK = 8   # Firefox takes up to ~25 s per scenario; keeps each file under the long timeout


def ndocs(s):
    return 1 + sum(1 for o in OPS[s] if o == 0)


def space():
    for st in range(2):
        for op in (range(4) if st == 0 else [0]):
            for sq, s in enumerate(SEQ):
                per = []
                for j in range(ndocs(s)):
                    ws = [0, 1] if j in TARGETS[s] else [0]
                    per.append([(r, c, w) for r in range(2) for c in range(4) for w in ws])
                for docs in itertools.product(*per):
                    yield st, op, sq, docs


def sid(x):
    st, op, sq, docs = x
    d = "-".join(RELc[r] + OPc[c] + ("w" if w else "") for r, c, w in docs)
    return "%s%s_%s_%s" % ("p" if st == 0 else "n", OPc[op], SEQ[sq], d)


def tla(x):
    st, op, sq, docs = x
    return "<<%d, %d, %d, <<%s>>>>" % (st + 1, op + 1, sq + 1,
                                     ", ".join("<<%d, %d, %d>>" % (r + 1, c + 1, w + 1) for r, c, w in docs))


def write_space(out):
    xs = list(space())
    with open(os.path.join(out, "HistorySpace.tla"), "w", encoding="utf-8") as f:
        f.write("---- MODULE HistorySpace ----\n(* generated by history/gen.py space *)\n")
        f.write("Space == <<\n  " + ",\n  ".join(tla(x) for x in xs) + ">>\n====\n")
    print("scenarios", len(xs))


PAGE = """<!DOCTYPE html>
<meta charset=utf-8>
<meta name=timeout content=long>
<title>OBS session history and bfcache, {label}</title>
<script src="/resources/testharness.js"></script>
<script src="/resources/testharnessreport.js"></script>
<script src="/common/dispatcher/dispatcher.js"></script>
<script src="/common/get-host-info.sub.js"></script>
<script src="/common/utils.js"></script>
<script src="resources/hws.sub.js"></script>
<script src="resources/hobs.js"></script>
<body>
<script>
const SCEN = [
{rows}
];
runHistory(SCEN).then(done);
</script>
"""
HEADERS = {"unsafe-none": "", "same-origin-allow-popups": "Cross-Origin-Opener-Policy: same-origin-allow-popups\n",
           "same-origin": "Cross-Origin-Opener-Policy: same-origin\n",
           "so+rc": "Cross-Origin-Opener-Policy: same-origin\nCross-Origin-Embedder-Policy: require-corp\n"}


def hdr(c):
    v = OP[c]
    return ("same-origin", "require-corp") if v == "so+rc" else (v, "unsafe-none")


def select(enum_out, hdir, seed=20261124, k=1, k0=8):
    # enum_out: one TLC output, or several (comma-separated, one per Lo..Hi range);
    # classes with the same key are merged.
    text = " ".join(re.sub(r"\s+", " ", open(p, encoding="utf-8").read()) for p in enum_out.split(","))
    xs = list(space())
    merged = {}
    for dl, dc, mem in re.findall(r'<< ?"class", \{([^}]*)\}, \{([^}]*)\}, \{([^}]*)\} ?>>', text):
        idx = [int(v) for v in mem.replace(" ", "").split(",") if v]
        key = (",".join(sorted(v.strip() for v in dl.split(",") if v.strip())),
               ",".join(sorted(v.strip() for v in dc.split(",") if v.strip())))
        merged.setdefault(key, []).extend(idx)
    classes = [(dl, dc, sorted(idx)) for (dl, dc), idx in merged.items()]
    rnd = random.Random(seed)
    chosen = set()
    for dl, dc, idx in sorted(classes):
        n = k if (dl or dc) else k0
        chosen.update(rnd.sample(idx, min(n, len(idx))))
    chosen = sorted(chosen)
    print("classes", len(classes), "chosen", len(chosen))
    tdir = os.path.join(hdir, "tests")
    os.makedirs(tdir, exist_ok=True)
    with open(os.path.join(hdir, "scenarios.tsv"), "w", encoding="utf-8") as f:
        f.write("sid\tindex\tstart\topener\tseq\tdocs\n")
        for i in chosen:
            st, op, sq, docs = xs[i - 1]
            f.write("%s\t%d\t%s\t%s\t%s\t%s\n" % (
                sid(xs[i - 1]), i, ST[st], OP[op], SEQ[sq],
                ",".join("%s/%s%s" % (REL[r], OP[c], "/ws" if w else "") for r, c, w in docs)))
    groups = {}
    for i in chosen:
        st, op, sq, docs = xs[i - 1]
        ds = ", ".join('{rel: "%s", coop: "%s", coep: "%s", ws: %s}' % ((REL[r],) + hdr(c) + ("true" if w else "false",))
                       for r, c, w in docs)
        groups.setdefault((st, op), []).append('  {id: "%s", st: "%s", ops: [%s], docs: [%s]},' % (
            sid(xs[i - 1]), ST[st], ", ".join(str(o) for o in OPS[SEQ[sq]]), ds))
    for (st, op), rows in sorted(groups.items()):
        for n in range(0, len(rows), CHUNK):
            stem = "h-%s%s-%02d.https.html" % ("p" if st == 0 else "n", OPc[op], n // CHUNK)
            with open(os.path.join(tdir, stem), "w", encoding="utf-8") as f:
                f.write(PAGE.format(label="%s, opener COOP %s" % (ST[st], OP[op]), rows="\n".join(rows[n:n + CHUNK])))
            if HEADERS[OP[op]]:
                with open(os.path.join(tdir, stem + ".headers"), "w", encoding="utf-8") as f:
                    f.write(HEADERS[OP[op]])
            print(stem, len(rows[n:n + CHUNK]))


if __name__ == "__main__":
    if sys.argv[1] == "space":
        write_space(sys.argv[2])
    else:
        select(sys.argv[2], sys.argv[3], *(int(a) for a in sys.argv[4:]))
