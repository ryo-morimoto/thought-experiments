"""Write Gen2Rows.tla from space.tsv (scenario order of Gen2Space.tla) and observed.tsv.

usage: python3 -I mkrows.py <space.tsv> <observed.tsv> <out dir>
Rows[r] = [id, s (index into Scen), k (kind), chrome, firefox], with the sets of
observed values ({} if not observed by that browser).
"""
import csv
import os
import sys

space_tsv, obs_tsv, outdir = sys.argv[1:4]
BROWSERS = ["chrome", "firefox"]
with open(space_tsv, encoding="utf-8") as f:
    idx = {r["sid"]: i for i, r in enumerate(csv.DictReader(f, delimiter="\t"), 1)}
obs = {}
with open(obs_tsv, encoding="utf-8") as f:
    for r in csv.DictReader(f, delimiter="\t"):
        sid, kind = r["row"].split(".", 1)
        obs.setdefault((sid, kind), {})[r["browser"]] = r["values"].split("|")
rows = []
for (sid, kind) in sorted(obs, key=lambda k: (idx[k[0]], k[1])):
    b = obs[(sid, kind)]
    sets = ["{%s}" % ", ".join('"%s"' % v for v in b.get(x, [])) for x in BROWSERS]
    rows.append('[id |-> "%s.%s", s |-> %d, k |-> "%s", chrome |-> %s, firefox |-> %s]'
                % (sid, kind, idx[sid], kind, sets[0], sets[1]))
with open(os.path.join(outdir, "Gen2Rows.tla"), "w", encoding="utf-8") as f:
    f.write("---- MODULE Gen2Rows ----\n(* generated by gen2/driver/mkrows.py *)\n")
    f.write("Browsers == {%s}\n" % ", ".join('"%s"' % b for b in BROWSERS))
    f.write("Rows == <<\n  " + ",\n  ".join(rows) + ">>\n====\n")
print("rows", len(rows))
