"""Write RedirectRows.tla: observed rows of the run scenarios.

usage: python3 -I mkrows.py <scenarios.tsv> <observed.tsv> <out dir>
Rows[r] = [id, x (space index), k (kind), chrome, firefox]; chrome/firefox
are the sets of observed values ({} if not observed). Kind "error" is not mapped.
Also WptRows: the upstream WPT redirect tests (driver/originals.txt) as
scenarios with their expected values, for the kill comparison.
"""
import csv
import os
import sys

scen_tsv, obs_tsv, outdir = sys.argv[1:4]
BROWSERS = ["chrome", "firefox"]
idx = {}
with open(scen_tsv, encoding="utf-8") as f:
    for r in csv.DictReader(f, delimiter="\t"):
        idx[r["sid"]] = int(r["index"])
obs = {}
with open(obs_tsv, encoding="utf-8") as f:
    for r in csv.DictReader(f, delimiter="\t"):
        sid, kind = r["row"].rsplit(".", 1)
        if kind == "error":
            continue
        obs.setdefault((sid, kind), {})[r["browser"]] = r["values"].split("|")
rows = []
for (sid, kind) in sorted(obs, key=lambda k: (idx[k[0]], k[1])):
    b = obs[(sid, kind)]
    sets = ["{%s}" % ", ".join('"%s"' % v for v in b.get(x, [])) for x in BROWSERS]
    rows.append('[id |-> "%s.%s", x |-> %d, k |-> "%s", chrome |-> %s, firefox |-> %s]' % (
        sid, kind, idx[sid], kind, sets[0], sets[1]))

# Upstream WPT redirect tests, encoded on the same axes (codes of RedirectSeq.tla).
# <<op, st, hops, fin>>, expected "opener" (popup has opener). coep-redirect: test
# page COOP same-origin + COEP require-corp (its .headers), all same-origin.
# popup-redirect-same-origin-allow-popups: opener sap; hop un (same/cross-origin; the
# test's cross origin is same-site www1); final sap at A. popup-redirect-cache:
# test page COOP same-origin; redirect and final both so+rc at the listed
# relations (O/S/X = same-origin/same-site/cross-site); caching is not on the axes.
WPT = [
    ("coep-redirect/coop-coep-to-coop-coep", "<<4, 1, <<<<1, 4>>>>, <<1, 3, 2>>>>", "TRUE"),
    ("coep-redirect/coop-coep-to-no-coop-coep", "<<4, 1, <<<<1, 4>>>>, <<1, 1, 2>>>>", "FALSE"),
    ("coep-redirect/none-to-coop-coep", "<<4, 1, <<<<1, 1>>>>, <<1, 3, 2>>>>", "FALSE"),
    ("coep-redirect/coop-nocoep-to-coop-coep", "<<4, 1, <<<<1, 3>>>>, <<1, 3, 2>>>>", "FALSE"),
    ("coep-redirect/un-coep-to-coop-coep", "<<4, 1, <<<<1, 1>>>>, <<1, 3, 2>>>>", "FALSE"),
    ("coep-redirect/un-coep-to-un-coep", "<<4, 1, <<<<1, 1>>>>, <<1, 1, 2>>>>", "FALSE"),
    ("popup-redirect-sap/same-origin", "<<2, 1, <<<<1, 1>>>>, <<1, 2, 1>>>>", "FALSE"),
    ("popup-redirect-sap/cross-origin", "<<2, 1, <<<<2, 1>>>>, <<1, 2, 1>>>>", "FALSE"),
    ("popup-redirect-cache/O-X", "<<3, 1, <<<<1, 4>>>>, <<3, 3, 2>>>>", "FALSE"),
    ("popup-redirect-cache/X-O", "<<3, 1, <<<<3, 4>>>>, <<1, 3, 2>>>>", "FALSE"),
    ("popup-redirect-cache/S-X", "<<3, 1, <<<<2, 4>>>>, <<3, 3, 2>>>>", "FALSE"),
]
with open(os.path.join(outdir, "RedirectRows.tla"), "w", encoding="utf-8") as f:
    f.write("---- MODULE RedirectRows ----\n(* generated by redirect/driver/mkrows.py *)\n")
    f.write("Browsers == {%s}\n" % ", ".join('"%s"' % b for b in BROWSERS))
    f.write("Rows == <<\n  " + ",\n  ".join(rows) + ">>\n")
    f.write("WptRows == <<\n  " + ",\n  ".join(
        '[id |-> "%s", sc |-> %s, k |-> "opener", want |-> "%s"]' % w for w in WPT) + ">>\n====\n")
print("rows", len(rows), "wpt", len(WPT))
