"""Generator of the redirect-chain popup scenarios (redirect/RESULTS.md).

usage:
  python3 -I gen.py space <out dir>          write RedirectSpace.tla (whole space)
  python3 -I gen.py select <tlc-enum.out> <redirect dir> [seed]
        pick scenarios from the pre-screen classes, write scenarios.tsv and tests/

Axes (codes as in RedirectSeq.tla):
  op   opener (test page at A) COOP: un, sap, so, so+rc (COOP same-origin + COEP require-corp)
  st   blank (window.open(chain)) | doc (popup first loads A with the opener's headers,
       then sets location to the chain)
  hops 0..2 redirects (302), each: origin relation to A {same-origin, same-site,
       cross-site} x COOP {un, sap, so, so+rc}
  fin  final response: relation x COOP {un, sap, so} x COEP {un, require-corp}
"""
import itertools
import os
import random
import re
import sys

OP = ["unsafe-none", "same-origin-allow-popups", "same-origin", "so+rc"]
OPc = ["u", "p", "s", "c"]
ST = ["blank", "doc"]
REL = ["same-origin", "same-site", "cross-site"]
RELc = ["O", "S", "X"]
FC = ["unsafe-none", "same-origin-allow-popups", "same-origin"]
FE = ["unsafe-none", "require-corp"]
CHUNK = 60


def space():
    hops = [(r, c) for r in range(3) for c in range(4)]
    fins = [(r, c, e) for r in range(3) for c in range(3) for e in range(2)]
    for op in range(4):
        for st in range(2):
            for nh in range(3):
                for hs in itertools.product(hops, repeat=nh):
                    for f in fins:
                        yield op, st, hs, f


def sid(x):
    op, st, hs, f = x
    h = "-".join(RELc[r] + OPc[c] for r, c in hs) or "0"
    return "%s_%s_%s_%s%s%s" % (OPc[op], st and "d" or "b", h, RELc[f[0]], OPc[f[1]], "r" if f[2] else "u")


def tla(x):
    op, st, hs, f = x
    return "<<%d, %d, <<%s>>, <<%d, %d, %d>>>>" % (
        op + 1, st + 1, ", ".join("<<%d, %d>>" % (r + 1, c + 1) for r, c in hs), f[0] + 1, f[1] + 1, f[2] + 1)


def write_space(out):
    xs = list(space())
    with open(os.path.join(out, "RedirectSpace.tla"), "w", encoding="utf-8") as f:
        f.write("---- MODULE RedirectSpace ----\n(* generated by redirect/gen.py space *)\n")
        f.write("Space == <<\n  " + ",\n  ".join(tla(x) for x in xs) + ">>\n====\n")
    print("scenarios", len(xs))


PAGE = """<!DOCTYPE html>
<meta charset=utf-8>
<meta name=timeout content=long>
<title>OBS redirect chains, opener COOP {label}</title>
<script src="/resources/testharness.js"></script>
<script src="/resources/testharnessreport.js"></script>
<script src="/common/dispatcher/dispatcher.js"></script>
<script src="/common/get-host-info.sub.js"></script>
<script src="/common/utils.js"></script>
<script src="resources/robs.js"></script>
<body>
<script>
const OPENER = {opener};
const SCEN = [
{rows}
];
runRedirect(SCEN).then(done);
</script>
"""
HEADERS = {"unsafe-none": "", "same-origin-allow-popups": "Cross-Origin-Opener-Policy: same-origin-allow-popups\n",
           "same-origin": "Cross-Origin-Opener-Policy: same-origin\n",
           "so+rc": "Cross-Origin-Opener-Policy: same-origin\nCross-Origin-Embedder-Policy: require-corp\n"}


def hdr(c):
    """(coop, coep) headers for a hop code (OP index)."""
    v = OP[c]
    return ("same-origin", "require-corp") if v == "so+rc" else (v, "unsafe-none")


def select(enum_out, rdir, seed=20261124):
    text = re.sub(r"\s+", " ", open(enum_out, encoding="utf-8").read())
    xs = list(space())
    classes = []
    for dl, dc, mem in re.findall(r'<< ?"class", \{([^}]*)\}, \{([^}]*)\}, \{([^}]*)\} ?>>', text):
        idx = [int(v) for v in mem.replace(" ", "").split(",") if v]
        classes.append((dl.strip(), dc.strip(), idx))
    rnd = random.Random(seed)
    chosen = set()
    for dl, dc, idx in sorted(classes):
        k = 2 if (dl or dc) else 12   # classes no mutant distinguishes: inclusion baseline
        chosen.update(rnd.sample(idx, min(k, len(idx))))
    chosen = sorted(chosen)
    print("classes", len(classes), "chosen", len(chosen))
    tdir = os.path.join(rdir, "tests")
    os.makedirs(tdir, exist_ok=True)
    with open(os.path.join(rdir, "scenarios.tsv"), "w", encoding="utf-8") as f:
        f.write("sid\tindex\topener\tstart\tnhops\thops\tfinal\n")
        for i in chosen:
            op, st, hs, fi = xs[i - 1]
            f.write("%s\t%d\t%s\t%s\t%d\t%s\t%s\n" % (
                sid(xs[i - 1]), i, OP[op], ST[st], len(hs),
                ",".join("%s/%s" % (REL[r], OP[c]) for r, c in hs),
                "%s/%s/%s" % (REL[fi[0]], FC[fi[1]], FE[fi[2]])))
    for op in range(4):
        rows = []
        for i in chosen:
            o, st, hs, fi = xs[i - 1]
            if o != op:
                continue
            hops = ", ".join('{rel: "%s", coop: "%s", coep: "%s"}' % ((REL[r],) + hdr(c)) for r, c in hs)
            rows.append('  {id: "%s", st: "%s", hops: [%s], fin: {rel: "%s", coop: "%s", coep: "%s"}},' % (
                sid(xs[i - 1]), ST[st], hops, REL[fi[0]], FC[fi[1]], FE[fi[2]]))
        for n in range(0, len(rows), CHUNK):   # chunks keep each file under the harness timeout
            stem = "op-%s-%02d.https.html" % (OPc[op], n // CHUNK)
            coop, coep = hdr(op)
            with open(os.path.join(tdir, stem), "w", encoding="utf-8") as f:
                f.write(PAGE.format(label=OP[op], opener='{coop: "%s", coep: "%s"}' % (coop, coep),
                                    rows="\n".join(rows[n:n + CHUNK])))
            if HEADERS[OP[op]]:
                with open(os.path.join(tdir, stem + ".headers"), "w", encoding="utf-8") as f:
                    f.write(HEADERS[OP[op]])
            print(stem, len(rows[n:n + CHUNK]))


if __name__ == "__main__":
    if sys.argv[1] == "space":
        write_space(sys.argv[2])
    else:
        select(sys.argv[2], sys.argv[3], *(int(a) for a in sys.argv[4:]))
