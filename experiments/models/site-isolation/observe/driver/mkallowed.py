"""Generate AllowedRows.tla (allowed output set per row and Mutant value) and
Observed.tla (observed values per browser and row) for AllowedSets.tla.

usage: python3 -I mkallowed.py <wpt-cases.tsv> <observed.tsv> <out dir>

Arguments are converted as in ../tsv2tla.py. Element loads (<img>, <script>;
rows whose wpt_path is image-loads.html, script-loads.html or
scheme-restriction.https.window.js) only expose load/error, so their allowed
set is projected with Proj (basic, opaque -> "load").
"""
import csv
import sys

ORIGINS = {
    "A": "OA", "Awww": "OAwww", "Awww2": "OAwww2", "B": "OB",
    "Ahttp": "OAhttp", "Awwwhttp": "OAwwwhttp", "Bhttp": "OBhttp",
}
ELEMENT_TESTS = ("image-loads.html", "script-loads.html", "scheme-restriction.https.window.js")


def lit(tok):
    if tok in ORIGINS:
        return ORIGINS[tok]
    if tok in ("TRUE", "FALSE"):
        return tok
    return '"%s"' % tok


def allowed_expr(op, args, element):
    a = [lit(x) for x in args]
    if op == "FetchResult":
        o, coep, mode, ro, corp, creds = a
        e = '{S(m)!FetchResult(%s, %s, %s, [origin |-> %s, corp |-> %s, creds |-> %s])}' % (
            o, coep, mode, ro, corp, creds)
        return "ProjSet(%s)" % e if element else e
    if op == "CrossOriginIsolated":
        x = ", ".join(a)
        # COIChoice: concrete (Mutant m) or logical. Under "logical" the getter is
        # FALSE whatever m does (COIChoice only enters COIMode's then-branch and
        # CrossOriginIsolated tests for "concrete"); computed from the logical run.
        return ('(IF "concrete" \\in COIChoices THEN {S(m)!CrossOriginIsolated(%s)} ELSE {}) \\cup '
                '(IF "logical" \\in COIChoices '
                'THEN {S("param:coi-logical")!CrossOriginIsolated(%s)} ELSE {})') % (x, x)
    if op == "OriginAgentCluster":
        o, coi, hist, hdr = a
        if coi == '"concrete"':
            return '{S(m)!OriginAgentCluster(S(m)!KeyKind(%s, c, %s, %s)) : c \\in COIChoices}' % (
                o, hist, hdr)
        return "{S(m)!OriginAgentCluster(S(m)!KeyKind(%s, %s, %s, %s))}" % (o, coi, hist, hdr)
    if op == "DocumentDomainNoOp":
        return "{S(m)!DocumentDomainNoOp(%s)}" % a[0]
    if op == "PopupSevered":
        return "{S(m)!PopupSevered(%s)}" % ", ".join(a)
    raise SystemExit("unknown operator " + op)


def obs_lit(v, element):
    v = v.strip()
    if v.lower() in ("true", "false"):
        return v.upper()
    return '"%s"' % v.replace('"', "'")


def main():
    cases, observed, out = sys.argv[1], sys.argv[2], sys.argv[3]
    rows = list(csv.DictReader(open(cases, encoding="utf-8"), delimiter="\t"))
    ids = ["w%03d" % i for i in range(1, len(rows) + 1)]
    arms, exp = [], []
    for rid, r in zip(ids, rows):
        element = any(t in r["wpt_path"] for t in ELEMENT_TESTS)
        args = [x.strip() for x in r["args"].split(",")]
        arms.append('     [] r = "%s" -> %s' % (rid, allowed_expr(r["operator"], args, element)))
        e = r["expected"].strip()
        if element:
            e = "error" if e == "error" else "load"
        exp.append('"%s" :> {%s}' % (rid, lit(e)))
    lines = [
        "----------------------------- MODULE AllowedRows -----------------------------",
        "(* Generated by observe/driver/mkallowed.py from ../wpt-cases.tsv. For each *)",
        "(* row r and Mutant value m, the set of outputs SpecIsolation allows.       *)",
        "EXTENDS Naturals, Sequences, FiniteSets, TLC",
        "VARIABLE dummy",
        "\\* Values of the model's parameter COIChoice to range over.",
        "CONSTANT COIChoices",
        "S(m) == INSTANCE SpecIsolation WITH Mutant <- m, dummy <- dummy",
        " \\* Origins do not depend on Mutant.",
    ] + ["%s == S(\"none\")!%s" % (v, v) for v in ORIGINS.values()] + [
        "Proj(v) == IF v = \"error\" THEN \"error\" ELSE \"load\"",
        "ProjSet(X) == {Proj(v) : v \\in X}",
        "RowSeq == <<%s>>" % ", ".join('"%s"' % i for i in ids),
        "Rows == {RowSeq[i] : i \\in 1..Len(RowSeq)}",
        "Allowed(m, r) ==",
        "  CASE " + arms[0].strip()[3:],
    ] + arms[1:] + [
        "\\* The TSV expected column, as pseudo-observations (pipeline check).",
        "Expected == " + " @@ ".join(exp),
        "===============================================================================",
        "",
    ]
    open(out + "/AllowedRows.tla", "w", encoding="utf-8").write("\n".join(lines))

    obs = {}  # browser -> row -> set of TLA literals
    for o in csv.DictReader(open(observed, encoding="utf-8"), delimiter="\t"):
        if o["value"] in ("unmapped", "held", ""):
            continue
        rid = o["row"]
        element = any(t in rows[int(rid[1:]) - 1]["wpt_path"] for t in ELEMENT_TESTS)
        for v in o["values"].split("|"):
            obs.setdefault(o["browser"], {}).setdefault(rid, set()).add(obs_lit(v, element))
    ol = [
        "------------------------------- MODULE Observed -------------------------------",
        "(* Generated by observe/driver/mkallowed.py from observed.tsv: every value a *)",
        "(* browser produced for a row, over both repeats and all sub-variants.      *)",
        "EXTENDS TLC",
        "Browsers == {%s}" % ", ".join('"%s"' % b for b in sorted(obs)),
    ]
    for b in sorted(obs):
        ol.append("Obs_%s == %s" % (b, " @@ ".join(
            '"%s" :> {%s}' % (rid, ", ".join(sorted(vs))) for rid, vs in sorted(obs[b].items()))))
    ol.append("Obs(b) == CASE " + "\n  [] ".join('b = "%s" -> Obs_%s' % (b, b) for b in sorted(obs)))
    ol += ["===============================================================================", ""]
    open(out + "/Observed.tla", "w", encoding="utf-8").write("\n".join(ol))
    print(len(rows), "rows;", {b: len(v) for b, v in obs.items()}, "observed rows per browser")


main()
